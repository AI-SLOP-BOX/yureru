/// Lookup function with safe fallback
String translate(String key, String langCode) {
  final langDict = _kTranslations[langCode] ?? _kTranslations['ja']!;
  return langDict[key] ??
      _kFeatureTranslations[langCode]?[key] ??
      _kScreenTranslations[langCode]?[key] ??
      _kExtraTranslations[langCode]?[key] ??
      _kLibraryTranslations[langCode]?[key] ??
      _kTranslations['ja']?[key] ??
      _kFeatureTranslations['ja']?[key] ??
      _kScreenTranslations['ja']?[key] ??
      _kExtraTranslations['ja']?[key] ??
      _kLibraryTranslations['ja']?[key] ??
      key;
}

